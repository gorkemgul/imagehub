# ruff: noqa: E501
"""MkDocs hook: builds the model, parity and gallery pages from the repository's own data.

Sources of truth (nothing below is typed by hand):

* ``imagehub/catalog.py``       model ids, families, revisions, licenses, image input
* ``docs/models.md``            the per-architecture prose, split into one page per catalog family
* ``docs/validation.json``      validation status and the recorded end-to-end differences
* ``docs/assets/gallery/*.json`` the reference-versus-imagehub image pairs

Generated pages are written into the docs directory (git-ignored) when the configuration loads,
so ``mkdocs serve`` and ``mkdocs build`` need no separate step. Placeholders such as
``<!-- ih:model-grid -->`` in hand-written pages are expanded in ``on_page_markdown``.
"""

from __future__ import annotations

import json
import posixpath
import re
import sys
from pathlib import Path

from markdown.extensions.toc import slugify

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from imagehub.catalog import MODEL_CATALOG  # noqa: E402

GENERATED_MARK = "<!-- generated by scripts/docs_hooks.py; do not edit -->\n"
# Titles for families whose first models.md section is a variant rather than the family itself.
FAMILY_TITLES = {"stable-diffusion": "Stable Diffusion"}
INLINE = re.compile(r"\{\{ ?ih\.([a-z-]+) ?\}\}")
TOKEN = re.compile(r"<!-- ih:([a-z-]+)(?::([^ ]+))? -->")

_cache: dict[str, object] = {}


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


# ----------------------------------------------------------------------------- data


def _load(docs: Path) -> dict:
    validation = json.loads((docs / "validation.json").read_text(encoding="utf-8"))
    status = {m["model_id"]: m for m in validation["models"]}

    gallery = {}
    for meta in sorted((docs / "assets/gallery").glob("*.json")):
        entry = json.loads(meta.read_text(encoding="utf-8"))
        gallery[entry["model_id"]] = entry

    # Split models.md into sections at top-level headings; assign each to a catalog family.
    text = (docs / "models.md").read_text(encoding="utf-8")
    parts = re.split(r"^# (.+)$", text, flags=re.M)
    sections = []  # (title, body, model ids)
    image_input_note = ""
    for title, body in zip(parts[1::2], parts[2::2], strict=True):
        head = body.split("**Architecture.**")[0]
        model_line = re.search(r"Models?:\s*(.+?)\s*·\s*Task:", head, flags=re.S)
        listed = re.findall(r"`([a-z0-9][a-z0-9._-]*)`", model_line.group(1)) if model_line else []
        if model_line and "…" in model_line.group(1):  # "`sd-v1-1` … `sd-v1-5`"
            ids = list(MODEL_CATALOG)
            first, last, *rest = listed
            listed = ids[ids.index(first) : ids.index(last) + 1] + rest
        if title == "Image input":
            image_input_note = body.strip()
            continue
        listed = [i for i in listed if i in MODEL_CATALOG]
        if not listed:
            raise SystemExit(f"docs/models.md: no catalog models found in the section {title!r}")
        sections.append((title, body.strip(), listed))

    placed = [i for _, _, ids in sections for i in ids]
    if sorted(placed) != sorted(MODEL_CATALOG):
        missing = sorted(set(MODEL_CATALOG) - set(placed))
        extra = sorted(i for i in placed if placed.count(i) > 1)
        raise SystemExit(f"docs/models.md does not cover the catalog once: {missing} {extra}")

    families: dict[str, dict] = {}
    for title, body, ids in sections:
        family = MODEL_CATALOG[ids[0]].family
        entry = families.setdefault(family, {"id": family, "sections": [], "models": []})
        entry["sections"].append((title, body, ids))
        entry["models"] += ids
    for entry in families.values():
        entry["title"] = FAMILY_TITLES.get(entry["id"], entry["sections"][0][0])
        entry["slug"] = entry["id"].replace("_", "-")
    return {
        "validation": validation,
        "status": status,
        "gallery": gallery,
        "families": families,
        "image_input_note": image_input_note,
    }


def data(config) -> dict:
    if "data" not in _cache:
        _cache["data"] = _load(Path(config["docs_dir"]))
    return _cache["data"]  # type: ignore[return-value]


# ----------------------------------------------------------------------------- helpers


def parity_of(entry: dict | None) -> tuple[str, str]:
    """(css class, label) for a model's recorded validation."""
    if not entry or entry.get("status") != "full":
        return "pending", "Not validated"
    e2e = entry.get("end_to_end") or {}
    if e2e.get("passed") is False:
        return "pending", "Failed"
    return "exact", "Parity · CPU fp32"


def model_family(model_id: str, d: dict) -> dict:
    return d["families"][MODEL_CATALOG[model_id].family]


def model_link(model_id: str, d: dict, from_uri: str) -> str:
    """Source-relative link (rewritten by MkDocs) to the section of a model's page."""
    family = model_family(model_id, d)
    target = posixpath.relpath(f"models/{family['slug']}.md", posixpath.dirname(from_uri) or ".")
    if len(family["sections"]) > 1:
        title = next(t for t, _, ids in family["sections"] if model_id in ids)
        target += "#" + slugify(title, "-")
    return target


def badges(model_id: str, d: dict) -> str:
    spec = MODEL_CATALOG[model_id]
    cls, label = parity_of(d["status"].get(model_id))
    inputs = '<span class="ih-badge ih-badge--in">Text</span>'
    if spec.image_input:
        inputs += '<span class="ih-badge ih-badge--in">Image</span>'
    return (
        f"{inputs}<span class='ih-arrow'>→</span><span class='ih-badge ih-badge--out'>Image</span>"
        f"<span class='ih-badge ih-badge--{cls}'>{label}</span>"
    )


def grid(d: dict, from_uri: str) -> str:
    cards = []
    for fam in d["families"].values():
        for model_id in fam["models"]:
            spec = MODEL_CATALOG[model_id]
            link = model_link(model_id, d, from_uri)
            cards.append(
                f'<div class="ih-card" data-search="{model_id} {fam["title"]} {spec.license}" markdown>\n\n'
                f"[`{model_id}`]({link}){{ .ih-card__title }}\n\n"
                f'<span class="ih-card__family">{fam["title"]}</span>\n\n'
                f'<span class="ih-card__badges">{badges(model_id, d)}</span>\n\n'
                f'<span class="ih-card__license">{spec.license}</span>\n\n'
                "</div>"
            )
    search = (
        '<input class="ih-filter" type="search" placeholder="Filter models, families, licenses" '
        'aria-label="Filter models">'
    )
    return f'{search}\n\n<div class="ih-grid" markdown>\n\n' + "\n\n".join(cards) + "\n\n</div>"


def compare(
    model_id: str, d: dict, prefix: str, caption: bool = True, *, turkish: bool = False
) -> str:
    """Before/after slider for one gallery pair; images use markdown so MkDocs fixes the paths."""
    g = d["gallery"][model_id]
    base = f"{prefix}assets/gallery/{model_id}"
    diff = g["max_pixel_diff"]
    if turkish:
        result = "pikseller aynı" if diff == 0 else f"maksimum piksel farkı {diff}"
        reference = "referans"
        slider_label = "Referans ile imagehub çıktısı arasında kaydır"
    else:
        result = "pixel-identical" if diff == 0 else f"max pixel difference {diff}"
        reference = "reference"
        slider_label = "Slide between the reference and imagehub output"
    figure = (
        f'<figure class="ih-compare" style="--pos:50%" markdown>\n'
        f'<span class="ih-compare__stage" markdown="span">'
        f"![{reference}]({base}.reference.webp){{ loading=lazy }}"
        f"![imagehub]({base}.imagehub.webp){{ .ih-compare__top loading=lazy }}"
        f'<input type="range" min="0" max="100" value="50" aria-label="{slider_label}">'
        f'<span class="ih-compare__tag ih-compare__tag--l">{reference}</span>'
        f'<span class="ih-compare__tag ih-compare__tag--r">imagehub</span></span>\n'
    )
    if caption:
        figure += (
            f"<figcaption><strong>{g['name']}</strong> · {g['settings']} · {result}</figcaption>\n"
        )
    return figure + "</figure>"


# ----------------------------------------------------------------------------- pages


def family_page(fam: dict, d: dict) -> str:
    multi = len(fam["sections"]) > 1
    out = [GENERATED_MARK, f"# {fam['title']}\n"]
    ids = fam["models"]
    out.append('<div class="ih-facts" markdown>\n')
    out.append("| Model | Source | Revision | Weight license | Parity (CPU, fp32) |")
    out.append("| --- | --- | --- | --- | --- |")
    for model_id in ids:
        spec = MODEL_CATALOG[model_id]
        repo = f"[{spec.repo_id}](https://huggingface.co/{spec.repo_id})" if spec.repo_id else "—"
        cls, label = parity_of(d["status"].get(model_id))
        tag = " (+ image input)" if spec.image_input else ""
        out.append(
            f"| `{model_id}`{tag} | {repo} | `{spec.revision[:7]}` | {spec.license} | {'Verified' if cls == 'exact' else label} |"
        )
    out.append("\n</div>\n")
    for title, body, _ in fam["sections"]:
        body = body.replace("](validation.md", "](../validation.md")
        body = re.sub(r"\]\(#([a-z0-9-]+)\)", lambda m: _anchor(m.group(1), d), body)
        if multi:
            out.append(f"## {title}\n")
            body = re.sub(r"^## ", "### ", body, flags=re.M)
        out.append(body + "\n")
    shown = [m for m in ids if m in d["gallery"]]
    if shown:
        out.append("## Reference and imagehub, side by side\n")
        out.append(
            "Drag the slider. Left is the recorded reference, right is imagehub, from the same "
            "seed, on CPU in float32.\n"
        )
        out.append('<div class="ih-gallery" markdown>\n')
        out.extend(compare(m, d, "../") + "\n" for m in shown)
        out.append("</div>\n")
    return "\n".join(out)


def _anchor(slug: str, d: dict) -> str:
    for fam in d["families"].values():
        for title, _, _ in fam["sections"]:
            if slugify(title, "-") == slug:
                return f"]({fam['slug']}.md#{slug})"
    return f"](#{slug})"


def models_index(d: dict) -> str:
    n_models, n_fam = len(MODEL_CATALOG), len(d["families"])
    image_note = d["image_input_note"]
    return (
        GENERATED_MARK
        + f"""# Models

{n_models} checkpoints in {n_fam} families, all behind `pipeline("t2i", backend=<model id>, ...)`.
Each family page has the architecture notes, settings, license and the recorded parity result.

<!-- ih:model-grid -->

## Image input

{image_note}

[Weights, licenses and pinned revisions](../catalog.md){{ .md-button }}
"""
    )


def results_table(d: dict, *, turkish: bool = False) -> str:
    if turkish:
        rows = [
            "| Model | Aile | Durum | Adım | Boyut | Latent maks. mutlak fark | Piksel maks. mutlak fark |"
        ]
    else:
        rows = ["| Model | Family | Status | Steps | Size | Latents max abs | Pixels max abs |"]
    rows.append("| --- | --- | --- | --- | --- | --- | --- |")
    for fam in d["families"].values():
        for model_id in fam["models"]:
            entry = d["status"].get(model_id) or {}
            e2e = entry.get("end_to_end") or {}
            lat = e2e.get("latents")
            lat = lat.get("max_abs") if isinstance(lat, dict) else None
            pix = e2e.get("pixels_max_abs", e2e.get("max_pixel_diff"))
            raw_size = e2e.get("size")
            size = (
                "×".join(str(x) for x in raw_size)
                if isinstance(raw_size, list)
                else str(raw_size or "—")
            )
            fmt = lambda v: "—" if v is None else (f"{v:g}" if isinstance(v, float) else str(v))  # noqa: E731
            rows.append(
                f"| [`{model_id}`](../models/{fam['slug']}.md) | {fam['title']} | "
                f"{entry.get('status', '—')} | {e2e.get('steps', '—')} | {size} | {fmt(lat)} | {fmt(pix)} |"
            )
    return "\n".join(rows)


def results_page(d: dict) -> str:
    env = d["validation"]["environment"]
    return (
        GENERATED_MARK
        + f"""# Results

One row per checkpoint, taken from `docs/validation.json`. A dash means that comparison was not the
form of evidence recorded for that model (some models are checked on tokens and pixels only, or against
        the model's recorded reference may be diffusers or its official implementation); the narrative record is in
[Validation](../validation.md).

Measured on CPU, float32, Python {env["python"]}, PyTorch {env["torch"]}, diffusers
{env["diffusers"]}, transformers {env["transformers"]} ({env["machine"]}).

"""
        + results_table(d)
        + "\n"
    )


def gallery_page(d: dict) -> str:
    out = [
        GENERATED_MARK,
        "# Gallery\n",
        f"{len(d['gallery'])} checkpoints, each generated twice from the same seed and prompt: once by "
        "the reference implementation (diffusers or the authors' code) and once by imagehub. Move the "
        "slider across a pair; identical outputs overlap completely. Images are downscaled to "
        "512 px for the web; the difference figures were "
        "measured on the full-size outputs.\n",
        '<div class="ih-gallery" markdown>\n',
    ]
    for fam in d["families"].values():
        for model_id in fam["models"]:
            if model_id in d["gallery"]:
                out.append(compare(model_id, d, "../") + "\n")
    out.append("</div>\n")
    return "\n".join(out)


def gallery_content(d: dict, *, turkish: bool = False) -> str:
    out = ['<div class="ih-gallery" markdown>\n']
    for fam in d["families"].values():
        for model_id in fam["models"]:
            if model_id in d["gallery"]:
                out.append(compare(model_id, d, "../", turkish=turkish) + "\n")
    out.append("</div>")
    return "\n".join(out)


# ----------------------------------------------------------------------------- hooks


def on_config(config):
    docs = Path(config["docs_dir"])
    d = data(config)
    for fam in d["families"].values():
        _write(docs / "models" / f"{fam['slug']}.md", family_page(fam, d))
    _write(docs / "models" / "index.md", models_index(d))
    _write(docs / "parity" / "results.md", results_page(d))
    _write(docs / "parity" / "gallery.md", gallery_page(d))

    # Fill the Models section of the navigation.
    for item in config["nav"]:
        if isinstance(item, dict) and "Models" in item:
            item["Models"] = ["models/index.md"] + [
                {fam["title"]: f"models/{fam['slug']}.md"} for fam in d["families"].values()
            ]
    return config


def on_page_markdown(markdown, page, config, files):
    d = data(config)
    turkish = page.file.src_uri.endswith(".tr.md")
    uri = page.file.src_uri.replace(".tr.md", ".md")
    depth_prefix = "../" * (posixpath.dirname(uri).count("/") + 1 if posixpath.dirname(uri) else 0)
    env = d["validation"]["environment"]

    def banner() -> str:
        path = Path(config["docs_dir"]) / "assets/banner.svg"
        if not path.exists():
            return ""
        rel = posixpath.relpath("assets/banner.svg", posixpath.dirname(uri) or ".")
        return f"![imagehub]({rel}){{ .ih-banner }}"

    replacements = {
        "models": str(len(MODEL_CATALOG)),
        "families": str(len(d["families"])),
        "validated": str(sum(1 for m in d["validation"]["models"] if m["status"] == "full")),
        "version": d["validation"]["version"],
        "date": d["validation"]["date"],
        "diffusers": env["diffusers"],
        "transformers": env["transformers"],
        "torch": env["torch"],
        "python": env["python"],
        "gallery-count": str(len(d["gallery"])),
        "max-pixel-diff": str(
            max(
                (
                    (m.get("end_to_end") or {}).get(
                        "pixels_max_abs", (m.get("end_to_end") or {}).get("max_pixel_diff", 0)
                    )
                    or 0
                    for m in d["validation"]["models"]
                ),
                default=0,
            )
        ),
    }

    def replace(match: re.Match) -> str:
        key = match.group(1)
        if key == "model-grid":
            return grid(d, uri)
        if key == "image-input":
            heading = (
                "| Model | Görüntü girdisi | Seçenek |"
                if turkish
                else "| Model | Image input | Option |"
            )
            rows = [heading, "| --- | --- | --- |"]
            rows += [
                f"| [`{m.id}`]({model_link(m.id, d, uri)}) | {m.image_input} | `image` |"
                for m in MODEL_CATALOG.values()
                if m.image_input
            ]
            return "\n".join(rows)
        if key == "results-table":
            return results_table(d, turkish=turkish)
        if key == "gallery":
            return gallery_content(d, turkish=turkish)
        if key == "banner":
            return banner()
        if key == "compare":
            return compare(match.group(2), d, depth_prefix, turkish=turkish)
        if key in replacements:
            return replacements[key]
        raise ValueError(f"{page.file.src_uri}: unknown placeholder ih:{key}")

    markdown = TOKEN.sub(replace, markdown)
    return INLINE.sub(lambda m: replacements[m.group(1)], markdown)
